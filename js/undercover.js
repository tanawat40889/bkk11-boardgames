export const MIN = 4, MAX = 10, RECENT = 40;
export const ROLE = { civ: 'พลเมือง', uc: 'Undercover', white: 'Mr. White' };

export function recommend(n) {
  if (n <= 4) return { uc: 1, white: 0 };
  if (n <= 6) return { uc: 1, white: 1 };
  if (n <= 8) return { uc: 2, white: 1 };
  return { uc: 3, white: 1 };
}

export function validate(n, uc, white) {
  const e = [];
  if (n < MIN) e.push(`ต้องมีผู้เล่นอย่างน้อย ${MIN} คน`);
  if (n > MAX) e.push(`ผู้เล่นได้สูงสุด ${MAX} คน`);
  if (uc < 1) e.push('ต้องมี Undercover อย่างน้อย 1 คน');
  if (white > 1) e.push('Mr. White ได้สูงสุด 1 คน');
  if (n - uc - white < uc + white + 1) e.push('พลเมืองต้องมากกว่าฝ่าย Undercover + Mr. White อย่างน้อย 1 คน');
  return e;
}

export function deal(sids, uc, white, recent = []) {
  let pool = PAIRS.map((_, i) => i).filter(i => !recent.includes(i));
  if (!pool.length) pool = PAIRS.map((_, i) => i);
  const pair = pool[rint(pool.length)];
  const flip = rint(2);
  const words = { civ: PAIRS[pair][flip], uc: PAIRS[pair][1 - flip] };
  const order = shuffle(sids), role = {};
  order.forEach((s, i) => (role[s] = i < uc ? 'uc' : i < uc + white ? 'white' : 'civ'));
  return { pair, words, sids: [...sids], role, alive: [...sids], out: [], votes: {}, cand: null, vr: 0, turn: 0, order: [], last: null, result: null, ready: [] };
}

export const wordOf = (g, s) => (g.role[s] === 'white' ? null : g.words[g.role[s]]);

// Random speaking order among the living; Mr. White never speaks first (if avoidable).
export function speakOrder(g) {
  const o = shuffle(g.alive);
  const i = o.findIndex(s => g.role[s] !== 'white');
  if (i > 0) [o[0], o[i]] = [o[i], o[0]];
  return o;
}

// Returns the sids with the most votes (only counting valid voters/targets).
export function tally(g) {
  const pool = g.cand || g.alive, cnt = {};
  pool.forEach(s => (cnt[s] = 0));
  for (const [v, t] of Object.entries(g.votes)) if (g.alive.includes(v) && t in cnt && t !== v) cnt[t]++;
  const max = Math.max(0, ...Object.values(cnt));
  return { cnt, top: max ? pool.filter(s => cnt[s] === max) : [...pool] };
}

export function eliminate(g, s) {
  g.alive = g.alive.filter(x => x !== s);
  g.out.push({ sid: s, role: g.role[s], turn: g.turn });
  return g.role[s];
}

export function winner(g) {
  const civ = g.alive.filter(s => g.role[s] === 'civ').length;
  const inf = g.alive.length - civ;
  if (!inf) return 'civ';
  if (civ <= 1) return 'inf';
  return null;
}

const norm = s => String(s || '').normalize('NFC').toLowerCase().replace(/[\s​.\-_'"]/g, '');
export const guessOk = (g, text) => !!norm(text) && norm(text) === norm(g.words.civ);

// who won -> per-player result
export function winners(g, w) {
  const out = {};
  const whiteOut = g.out.some(o => g.role[o.sid] === 'white');
  for (const s of g.sids) {
    const r = g.role[s];
    out[s] = w === 'white' ? r === 'white' : w === 'civ' ? r === 'civ' : r === 'uc' || (r === 'white' && !whiteOut);
  }
  return out;
}
