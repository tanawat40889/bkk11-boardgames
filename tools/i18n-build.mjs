// Writes js/i18n-en.js from a { thai: english } JSON (sorted, one entry per line, so diffs stay readable).
//   node tools/i18n-build.mjs dict.json
import { readFileSync, writeFileSync } from 'node:fs';
const d = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const keys = Object.keys(d).sort((a, b) => a.localeCompare(b, 'th'));
const out = `// English for every Thai text the app shows (generated by tools/i18n-build.mjs; add new keys with tools/i18n-extract.mjs).
// {} marks an interpolated value; English may reorder them as {1} {2} …
export const EN = {
${keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(d[k])},`).join('\n')}
};
// Same Thai word, different meaning per game.
export const EN_GAME = {
  onuw: { 'โจร': 'Robber' },
  bd: { 'นายอำเภอ': 'Sheriff', 'โจร': 'Outlaw' },
};
`;
writeFileSync(new URL('../js/i18n-en.js', import.meta.url), out);
console.log(keys.length, 'entries');
